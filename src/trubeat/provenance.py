"""Content-provenance check: C2PA Content Credentials (docs/11 D2).

A C2PA manifest whose actions declare an IPTC digital source type of
``trainedAlgorithmicMedia`` (or a composite containing it) is the generator
saying, in a signed record, that the content is AI-generated. When present
it is near-definitive; when absent it proves nothing, because re-encoding,
screen recording and most re-shares strip the manifest.

Offline by construction: remote-manifest fetching and OCSP lookups are
disabled, so reading provenance makes no network call (AGENTS.md §7).
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path

# IPTC digital source types that mean "generated by a trained model".
# https://cv.iptc.org/newscodes/digitalsourcetype/
AI_SOURCE_TYPES = (
    "trainedAlgorithmicMedia",
    "compositeWithTrainedAlgorithmicMedia",
)

# c2pa-rs settings: never fetch remote manifests or OCSP responses. (The
# SDK accepts unknown keys silently; these two names were checked against
# the bundled libc2pa_c.so.)
OFFLINE_SETTINGS = {"verify": {"remote_manifest_fetch": False, "ocsp_fetch": False}}


@dataclass
class ProvenanceResult:
    has_c2pa: bool = False
    ai_declared: bool = False  # a manifest declares trained-model generation
    source_types: list[str] = field(default_factory=list)
    generator: str | None = None  # claim generator / software agent, if named
    validation_state: str | None = None  # SDK's verdict on the signature chain
    warnings: list[str] = field(default_factory=list)

    def to_json(self) -> str:
        return json.dumps(asdict(self))


def _walk(obj):
    """Yield every dict nested anywhere in a JSON-like structure."""
    if isinstance(obj, dict):
        yield obj
        for v in obj.values():
            yield from _walk(v)
    elif isinstance(obj, list):
        for v in obj:
            yield from _walk(v)


def _agent_name(agent) -> str | None:
    if isinstance(agent, str):
        return agent
    if isinstance(agent, dict):
        name = agent.get("name")
        version = agent.get("version")
        if name:
            return f"{name} {version}".strip() if version else str(name)
    return None


def interpret_manifest_store(store: dict) -> ProvenanceResult:
    """Pure interpretation of a C2PA manifest-store JSON (``Reader.json()``).

    Scans every manifest, including ingredients' manifests, for actions
    carrying ``digitalSourceType``. A trained-model source type anywhere in
    the history counts: an edited AI clip is still AI-derived.
    """
    res = ProvenanceResult(has_c2pa=True)
    types: list[str] = []
    for d in _walk(store):
        dst = d.get("digitalSourceType")
        if isinstance(dst, str):
            short = dst.rstrip("/").rsplit("/", 1)[-1]
            if short not in types:
                types.append(short)
            if short in AI_SOURCE_TYPES and res.generator is None:
                res.generator = _agent_name(d.get("softwareAgent"))
    res.source_types = types
    res.ai_declared = any(t in AI_SOURCE_TYPES for t in types)
    active = store.get("active_manifest")
    manifests = store.get("manifests") or {}
    if res.generator is None and isinstance(manifests, dict) and active in manifests:
        m = manifests[active]
        info = m.get("claim_generator_info")
        if isinstance(info, list) and info:
            res.generator = _agent_name(info[0])
        res.generator = res.generator or m.get("claim_generator")
    res.validation_state = store.get("validation_state")
    if res.ai_declared and res.validation_state not in (None, "Valid", "Trusted"):
        res.warnings.append(
            f"W_C2PA_UNVERIFIED: manifest declares AI generation but its "
            f"validation state is {res.validation_state!r}"
        )
    return res


def read_provenance(path: str | Path) -> ProvenanceResult:
    """Read C2PA Content Credentials from a media file, offline.

    Never raises: a missing library, an unreadable file or a malformed
    manifest come back as a result with a warning.
    """
    p = Path(path)
    if not p.is_file():
        return ProvenanceResult(warnings=[f"E_UNREADABLE: not a file: {path}"])
    try:
        import c2pa
    except ImportError:
        return ProvenanceResult(warnings=["W_NO_C2PA_LIB: c2pa-python not installed"])
    try:
        ctx = c2pa.Context(c2pa.Settings.from_dict(OFFLINE_SETTINGS))
        reader = c2pa.Reader.try_create(str(p), context=ctx)
        if reader is None:
            return ProvenanceResult()
        try:
            store = json.loads(reader.json())
        finally:
            reader.close()
    except Exception as exc:  # noqa: BLE001 - provenance must never break analysis
        return ProvenanceResult(warnings=[f"W_C2PA_READ: {type(exc).__name__}: {exc}"])
    return interpret_manifest_store(store)
